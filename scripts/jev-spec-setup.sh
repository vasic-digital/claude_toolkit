#!/usr/bin/env bash
# jev-spec-setup.sh — opt-in CI template installer for jev-spec
# (design: toolkit-jev-design §2.9). NOT part of the default jev-setup.
#
# Usage: jev-spec-setup [--force] /path/to/target-repo
#
# Writes two templates into the target repo (refuses to overwrite without
# --force; never runs npm install itself — prints the command instead):
#   jev-spec.config.ts                spec requirement <-> codePaths targets
#   .github/workflows/jev-verify.yml  PR verification workflow
#
# KEY-NAME NOTE: jev-spec reads TYPESAFE_AI_API_KEY (verified jev-spec README)
# — deliberately different from the runtime SDK convention TYPESAFE_API_KEY
# used by jev-gate.sh / jev_mcp.py. Both names are real; do not "unify" them.
set -uo pipefail

FORCE=0 TARGET=""
while [ $# -gt 0 ]; do
  case "$1" in
    --force) FORCE=1; shift ;;
    -h|--help) grep '^#' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) TARGET="$1"; shift ;;
  esac
done

if [ -z "$TARGET" ] || [ ! -d "$TARGET" ]; then
  printf 'usage: jev-spec-setup [--force] /path/to/target-repo\n' >&2
  exit 2
fi

_write_template() { # _write_template <path> — stdin is content
  local path="$1"
  if [ -e "$path" ] && [ "$FORCE" != 1 ]; then
    printf 'jev-spec-setup: REFUSING to overwrite %s (use --force)\n' "$path" >&2
    return 1
  fi
  mkdir -p "$(dirname "$path")"
  local tmp="$path.jevtmp.$$"
  cat > "$tmp" && mv "$tmp" "$path"
  printf 'jev-spec-setup: wrote %s\n' "$path"
}

rc=0

_write_template "$TARGET/jev-spec.config.ts" <<'TS_EOF' || rc=1
// jev-spec.config.ts — generated by jev-spec-setup (claude_toolkit).
// One focused question per spec requirement; each requirement maps to the
// code paths that must satisfy it. jev-spec reads TYPESAFE_AI_API_KEY
// (note: NOT TYPESAFE_API_KEY — the names differ by design).
import { defineConfig } from "jev-spec";

export default defineConfig({
  model: "jev-latest",
  requirements: [
    {
      id: "example-no-secret-logging",
      spec: "No code path logs API keys, tokens, or the raw contents of api_keys.sh.",
      codePaths: ["src/**"],
      question: "Could any statement in these files write secret material to logs, stdout, or error messages?",
    },
  ],
});
TS_EOF

_write_template "$TARGET/.github/workflows/jev-verify.yml" <<'YML_EOF' || rc=1
# jev-verify.yml — generated by jev-spec-setup (claude_toolkit).
# Verifies spec requirements against the PR diff with a Jev decision model.
# The key is NEVER exposed to fork PRs: forks get --dry-run (report shape
# only, no model calls).
name: jev-spec verify
on:
  pull_request:

permissions:
  contents: read

jobs:
  jev-spec:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0
      - uses: oven-sh/setup-bun@0c5077e51419868618aeaa5fe8019c62421857d6 # v2.2.0
      - name: Install jev-spec
        run: bunx jev-spec --version
      - name: Verify (trusted PRs)
        if: github.event.pull_request.head.repo.full_name == github.repository
        env:
          TYPESAFE_AI_API_KEY: ${{ secrets.TYPESAFE_AI_API_KEY }}
        run: |
          bunx jev-spec check --diff origin/main...HEAD --format markdown \
            >> "$GITHUB_STEP_SUMMARY"
      - name: Verify (fork PRs, dry-run)
        if: github.event.pull_request.head.repo.full_name != github.repository
        run: |
          bunx jev-spec check --diff origin/main...HEAD --dry-run \
            --format markdown >> "$GITHUB_STEP_SUMMARY"
YML_EOF

if [ "$rc" = 0 ]; then
  printf '\nNext steps (never run automatically):\n'
  printf '  cd %s && npm i -D jev-spec\n' "$TARGET"
  printf '  Add the TYPESAFE_AI_API_KEY repo secret, edit jev-spec.config.ts requirements.\n'
fi
exit "$rc"
